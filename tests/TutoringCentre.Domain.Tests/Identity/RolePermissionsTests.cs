    [Fact]
    public void Owner_HoldsEveryStaffPermission()
    {
        Assert.Equal(26, Permissions.All.Count);
        Assert.All(Permissions.All.Where(permission => permission != Permissions.ConversationsIngest), permission => Assert.True(RolePermissions.Holds(StaffRole.Owner, permission)));
    }

    [Theory]
    [InlineData(StaffRole.Owner)]
    [InlineData(StaffRole.Secretary)]
    [InlineData(StaffRole.Teacher)]
    public void For_OnlyReturnsPermissionsFromTheCatalogue(StaffRole role)
    {
        Assert.All(RolePermissions.For(role), permission => Assert.Contains(permission, Permissions.All));
    }

    [Theory]
    [InlineData(StaffRole.Owner)]
